var a = Number(prompt("Digite A:"));
var b = Number(prompt("Digite B:"));
var c = Number(prompt("Digite C:"));
var d = Number(prompt("Digite D:"));

console.log("A + B = " + (a + b));
console.log("A * B = " + (a * b));
console.log("A + C = " + (a + c));
console.log("A * C = " + (a * c));
console.log("A + D = " + (a + d));
console.log("A * D = " + (a * d));
console.log("B + C = " + (b + c));
console.log("B * C = " + (b * c));
console.log("B + D = " + (b + d));
console.log("B * D = " + (b * d));
console.log("C + D = " + (c + d));
console.log("C * D = " + (c * d));
