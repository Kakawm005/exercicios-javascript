// Manzano - L01_COMPL_A: Produto (A*C) e soma (B+D) de quatro inteiros

var a = Number(prompt("Digite A:"));
var b = Number(prompt("Digite B:"));
var c = Number(prompt("Digite C:"));
var d = Number(prompt("Digite D:"));
var p = a * c;
var s = b + d;
console.log("P (A * C) = " + p);
console.log("S (B + D) = " + s);
